function hasBatchim(text) {
  const ch = text.charCodeAt(text.length - 1);
  if (ch < 0xac00 || ch > 0xd7a3) return false;
  return (ch - 0xac00) % 28 !== 0;
}

function josa(text, batchim, noBatchim) {
  return hasBatchim(text) ? batchim : noBatchim;
}

