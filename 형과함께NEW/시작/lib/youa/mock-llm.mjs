function matrixCardBody(card, facts) {
  const fullTitle = facts.child.fullTitle;
  const parentLabel = card.header.match(/(어머님|아버님)/)?.[0] ?? '부모님';

  const part1 = `${parentLabel}의 사주에는 ${card.axisKorean} 결이 자리합니다.`;
  const part2 = `${fullTitle}은 ${card.factorKorean} 결이 ${card.factorKorean === '끈기' ? '한 자리에 꾸준히 들고 가는' : card.factorKorean === '흔들림' ? '깊이 느끼는' : card.factorKorean === '어울림' ? '공감적인' : '신중한'} 결입니다.`;
  const part3 = `이 두 결이 만나면 ${card.tone}.`;
  const daily = `🌸 일상에서는…\n• ${parentLabel}과 함께하는 자리에서 ${fullTitle}의 ${card.factorKorean} 결이 자연스럽게 드러나는 모습이 보입니다.`;
  const advice = card.isConflict
    ? `🌿 이렇게 풀어보세요: ${parentLabel}의 ${card.axisKorean} 결을 부드럽게 푸시면 ${fullTitle}의 ${card.factorKorean} 결과 더 자연스러운 자리가 됩니다.`
    : '';

  return `${part1} ${part2} ${part3}\n\n${daily}${advice ? '\n\n' + advice : ''}`;
}

