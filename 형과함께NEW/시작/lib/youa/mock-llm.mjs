function factorBody(facts, fkey) {
  const f = facts.childFactors[fkey];
  const fullTitle = facts.child.fullTitle;
  const factorKo = FACTOR_KO[fkey];
  const obj = josa(factorKo, '을', '를');

  return `${fullTitle}의 ${factorKo} ${f.score}점은 사주에서 ${factorKo}${obj} 만드는 기운과 누르는 기운이 함께 결합되어 나온 결과입니다. 어떤 인자들이 어떻게 작용했는지 살펴봅니다.`;
}

