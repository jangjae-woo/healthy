// 처방용 helper — elements에서 가장 약한 / 강한 오행 추출
export function sortedWeakest(elements: Record<string, number>): string {
  const sorted = Object.entries(elements).sort((a, b) => (a[1] as number) - (b[1] as number));
  return sorted[0]?.[0] ?? "목";
}
export function sortedStrongest(elements: Record<string, number>): string {
  const sorted = Object.entries(elements).sort((a, b) => (b[1] as number) - (a[1] as number));
  return sorted[0]?.[0] ?? "목";
}

