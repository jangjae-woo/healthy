function bonneungSubsFor(relationship: RelationshipKind, aName: string, bName: string): string {
  const subs = BONNEUNG_BY_RELATIONSHIP[relationship];
  return subs.map(s => {
    const guide = s.guide.replace(/__A__/g, aName).replace(/__B__/g, bName);
    return `### ${s.title}\n${guide}`;
  }).join("\n\n");
}

