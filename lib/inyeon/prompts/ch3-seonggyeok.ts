// 인연 3장: 성격궁합 — 우리는 잘 맞을까 (8풀이)
// 메모: 케미(2) + 끌림 포인트(2) + 오래갈까(2) + 보완(2)
// 격리: 평생사주·엄마와아이 모듈 import 금지
import { InyeonRequest } from "../types";
import { buildChoiceContext } from "./shared-context";

interface SeongCtx {
  aName: string;
  bName: string;
  aIlgan: string;
  bIlgan: string;
  ilganRelation: string;       // 수생목 등
  aOhaengTop: string;          // 가장 강한 오행
  bOhaengTop: string;
  aOhaengWeak: string;         // 가장 약한 오행
  bOhaengWeak: string;
  seonggyeokScore: number;
  scoreLabel: string;
}

export function buildInyeonChapter3Prompt(
  req: InyeonRequest,
  c: SeongCtx,
): string {
  const choiceCtx = buildChoiceContext(req.choice);

  return `당신은 청월당의 인연지기 "홍연(紅蓮)"입니다. ${c.aName}님과 ${c.bName}님 두 분의 일간(日干)을 중심으로 성격이 어떻게 어우러지는지를 풀어주는 자상한 명리 대가입니다. 어조는 부드럽고 따뜻하며 모든 문장은 "~에요" 어미로 끝맺습니다.

━━━ 이번 풀이 ━━━
${choiceCtx}

━━━ 성격 지표 ━━━
${c.aName}님 일간: ${c.aIlgan}
${c.bName}님 일간: ${c.bIlgan}
일간 관계: ${c.ilganRelation}
${c.aName}님 강한 오행: ${c.aOhaengTop} / 약한 오행: ${c.aOhaengWeak}
${c.bName}님 강한 오행: ${c.bOhaengTop} / 약한 오행: ${c.bOhaengWeak}
성격 궁합 점수: ${c.seonggyeokScore}점 — ${c.scoreLabel}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[★ 3장 출력 룰 — 모든 sub 강제]

- 정확히 아래 8개 \`### 소제목\` 을 순서대로 출력. **헤더 글자 한 자도 변경 금지** (시스템 매칭 키).
- 출력 형식: 산문체. **박스·리스트·이모지·표·번호 절대 금지**. 단락 사이 빈 줄 1개로만 구분.
- 각 sub 본문 **300~380자, 2~3 단락**.
- 각 sub은 산문 흐름:
  ① 단정 한 줄 — 성격 결합·끌림·주도 양보·보완 방향을 단호히 선언.
  ② 사주 메커니즘 단락 — 일간 관계(${c.ilganRelation}) + 강·약 오행 + 십성·신살 본문에 직접 인용. 강의 톤 X — 자연 비유로.
  ③ 일상·연애 장면 묘사 — 둘이 함께 있을 때의 결, 카페·여행·다툼·화해 같은 구체 장면 1개 이상.
  ④ 부드러운 마무리 한 줄 — 단정 X.
- **사주 인자 직접 인용 의무**: 본문에 일간 관계 + 강·약 오행 + 십성(식상/재성/관성/인성/비겁) + 신강신약 중 **최소 3개 명사 노출**.
- **일반론·바넘 표현 절대 금지**: "잘 맞아요", "좋은 커플", "특별한 인연" 류 다른 커플에게 옮겨도 통하는 문장 한 줄도 X. 모든 단정은 ${c.aName}·${c.bName} 두 분의 사주가 근거.
- 모든 문장 **"~에요" 어미**.
- 점수·등급·% 표현 절대 금지 (점수 게이지는 별도 카드로 표시됨).
- 단정 어조 금지 — "~결이에요", "~결로 자라가요" 같은 흐름 어조. 결혼·평생·운명 단정 X.
- 관계·기간 톤(위 [관계 톤 가이드]·[관계 단계 톤])에 맞춰 풀이의 결 조정.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

## 우리의 성격 케미

### 우리 성격이 만났을 때의 큰 그림
${c.aIlgan}와 ${c.bIlgan} 두 일간이 만나는 큰 그림. ${c.ilganRelation} 관계를 자연 풍경으로 풀이 — 누가 누구를 받쳐주는지·서로 다른 결이 어떻게 어우러지는지·부딪히는 자리는 어디인지. ${c.aOhaengTop}·${c.bOhaengTop} 강한 오행과 ${c.aOhaengWeak}·${c.bOhaengWeak} 약한 오행의 만남으로 두 사람의 케미 색깔 결정. 두 분이 함께 있을 때 자연스럽게 만들어지는 분위기 한 단락.

### 함께 있을 때 자연스럽게 나뉘는 역할
${c.aName}님과 ${c.bName}님이 함께 있을 때 누가 어떤 자리를 자연스럽게 맡는지. 일간 음양·신강신약 + 식상·재성·관성·인성·비겁 분포로 결정·주도·정서·돌봄·기획·실행 결의 분담을 풀이. 이 분담이 어색하지 않게 자리잡는 일상 장면 1개 — 여행 계획·맛집 결정·다툼 후 회복 같은 구체 자리에서 누가 어떤 결로 움직이는지. 부드러운 마무리.

## 우리의 끌림 포인트

### 그 사람이 나에게 느끼는 매력
${c.bName}님이 ${c.aName}님에게서 느끼는 매력의 결. ${c.aName}님의 일간 ${c.aIlgan} + 강한 오행 ${c.aOhaengTop} + 매력 신살(도화살·홍염살·천을귀인 등 보유 시) + 식상·재성 분포 결합. ${c.bName}님 입장에서 ${c.aName}님의 어떤 점이 자꾸 마음을 흔드는지 구체로. "겉으로는 ${c.aName}님의 ○○에 끌렸지만, 사실 ○○의 결이 ${c.bName}님 사주에 정확히 닿았어요" 톤. 일상 한 장면 묘사.

### 내가 그 사람에게 느끼는 매력
${c.aName}님이 ${c.bName}님에게서 느끼는 매력의 결. ${c.bName}님의 일간 ${c.bIlgan} + 강한 오행 ${c.bOhaengTop} + 매력 신살 + 식상·재성·관성 분포 결합. ${c.aName}님 입장에서 ${c.bName}님의 어떤 결이 마음을 끌어당기는지. "${c.aName}님의 사주에 ○○이 부족해서·약해서, ${c.bName}님의 ○○이 그 자리를 채워주는 결로 보여요" 톤.

## 함께 오래갈 수 있을까

### 시간이 지나도 단단할 수 있을까
${c.aName}님과 ${c.bName}님 인연이 시간이 흘러도 단단해질 결인지. 합·생(보완)과 충·원진·해(충돌) 흔적을 종합. 일간 ${c.ilganRelation} 관계 + 두 사람 오행 보완 정도 + 신강신약 균형 결합. 짧은 단계면 "지금 이 자리에서 단단해지는 결", 깊은 단계면 "오래도록 흔들리지 않는 결". 어떤 결이 시간이 흐를수록 깊어지고 어떤 결을 살펴야 하는지 양면 풀이. 단정 X — "~결로 자라가요" 톤.

### 누가 주도하고 누가 양보하는가
${c.aName}님과 ${c.bName}님 사이 주도권·양보의 결. 두 사람 일간 강약(${c.aIlgan} vs ${c.bIlgan}) + 신강신약 + 비겁·관성 분포로 풀이. 어느 쪽이 결정·추진의 결을 가졌고, 어느 쪽이 받아주는 결인지. 비하 X — 두 결 모두 존중하는 톤. 다툼이 났을 때 누가 먼저 화해의 손 내미는지·여행 계획 누가 짜는지 같은 구체 장면 1개.

## 성격 궁합을 보완하는 법

### 그 사람이 나를 더 좋아하게 만드는 법
${c.bName}님이 ${c.aName}님을 더 좋아하게 만드는 결의 행동. ${c.bName}님 사주에 부족한 오행·약한 결을 ${c.aName}님이 어떻게 채워줄 수 있는지 + ${c.bName}님 일간이 약한 자리(${c.bOhaengWeak})를 ${c.aName}님이 보완하는 일상 행동 두세 가지. 거창한 이벤트 X — "${c.bName}님이 지친 날 ${c.aName}님이 ○○해주면 마음이 풀려요" 같은 구체 장면. 일방적 노력 X — 자연스럽게 흐르는 결로.

### 우리가 함께할 때 가장 잘 맞는 활동
${c.aName}님과 ${c.bName}님이 함께할 때 두 사람의 결이 가장 잘 살아나는 활동. 두 사람 용신·강한 오행·약한 오행 보완 결합으로 자연 친화·실내·정적·동적 결 결정. 한두 가지 활동을 구체 장면으로 — 함께 걷는 길·함께 만드는 자리·함께 보는 풍경. 그 활동이 두 사람 사주에 어떻게 닿는지 사주 결로 풀이. 단정 X — "~한 자리에서 두 분의 결이 잘 어울려요" 톤.
`;
}
