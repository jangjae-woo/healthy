// 둘의 홍실(인연궁합 V2) V2 원칙 — 자도인 V2의 강점을 두 사람 + 6 관계 분기 톤으로 적응
// 모든 챕터 프롬프트에 강제 주입.

export const INYEON_V2_PRINCIPLES = (aName: string, bName: string) => `
[★★★ 인연궁합 공통 원칙]

A. **사주 용어 노출**
   - 각 소제목 본문에서 메인 인자 한자병기 1회만 허용. 이후 본문은 부드러운 한국어로 자연 등장.
   - 격국명·격국 분류는 인연궁합 본문에 쓰지 말 것.
   - 신살명(도화살·홍염살·천을귀인·원진살 등)은 한자 병기 1회 허용.

B. **글 모양 다양화**
   - 모든 sub가 동일 산문체 템플릿이면 AI 템플릿 느낌으로 들통남.
   - 각 소제목은 지정된 패턴을 따르되, 첫 문장·단락 리듬·장면 소재가 서로 달라야 함.
   - 한 챕터 안에서 같은 첫 줄 패턴을 반복하지 말 것.

C. **첫 줄 cadence 풀**
   - 한 챕터 안에서 같은 cadence 두 번 금지.
   - 선택지:
     1) **캐치프레이즈 단정형**: "두 분은 [구체 결]의 인연이에요" / "${aName}님과 ${bName}님 사이엔 [[키워드]]가 흘러요"
     2) **질문 던지기형**: "두 분은 어떤 결로 만난 인연일까요?" 또는 "${bName}님이 ${aName}님의 어디에 마음이 흔들렸을까요?"
     3) **한 컷 묘사 시작형**: "카페에서 마주 앉아 ${aName}님이 살짝 웃을 때, ${bName}님은 — …" (장면 먼저, 풀이는 그 다음)
     4) **자연 비유 시작형**: "${aName}님의 큰 강 같은 결과 ${bName}님의 한낮 태양 같은 결이 만나면 — …"
     5) **시간 묘사형**: "두 분이 처음 마주친 그 자리에서 …" / "이 인연에 시간이 흐르면 …"
     6) **양방향 도입형**: "${aName}님 시선에서는 …, ${bName}님 시선에서는 …" (양방향 두 갈래로 시작)
   - 양방향 분리 묘사형 sub은 6번 cadence 의무.

D. **깊이와 개인화**
   - 결론만 쓰고 끝내지 말고, 메인 인자와 서브 인자 2~3개가 어떻게 연결되는지 보여줄 것.
   - 단일 인자 풀이 금지.
   - 두 사람 사주 데이터(컨텍스트 블록)에서 메인·서브 인자값을 모두 확인 후, ${aName}님·${bName}님 두 분에게만 해당하는 풀이 작성. 일반론 금지.
   - 빈 형용사·뻔한 소리 금지.

E. **십성·오행 강도 분기**
   - **강함** → 그 결이 두드러지는 결로 풀이.
   - **중간** → 양면 풀이.
   - **약함** → 옅은 결로 작동 + 다른 결이 채워주는 자리 풀이.
   - **0(없음) — 양면 풀이 강제**: 결핍 낙인 X — 그 결이 비어있는 만큼 다른 결로 채워지는 자연스러운 흐름으로 풀이.
   - "○○이 약해서 보완해야 합니다" 패턴 절대 금지.
   - 이 prompt에 인용된 안내 어휘를 본문에 그대로 박지 말 것.

F. **두 분 어조 보호** — "맞지 않는/문제 있는/약한 인연" 금지. "단단하게 자라는/시간이 깊어지는/서로 채워주는 결" 등 양면 모두 존중. 한쪽 비하 절대 X — 두 결 모두 존중.

G. **이름 고정 룰** — 이름은 입력값 그대로만 사용. \`${aName}님\`, \`${bName}님\` 외의 변형·중복 글자·별칭을 만들지 말 것.

H. **두 분 호명 다양성** — "두 분"·"${aName}님과 ${bName}님"·"이 두 결" 등 표현 다양화. 같은 호명 반복 금지.

I. **사건 확정·정량 표현 금지** — 점수·% 직접 인용 X. "운명적", "반드시", "평생" 같은 사건 확정 X. 가능성 어조.

J. **마크다운 헤더 정확 출력** — 챕터 헤더는 \`## …\`, 소제목은 \`### …\`. 헤더 텍스트 한 자도 바꾸지 말 것.

K. **관계 분기 톤 충실** — 짝사랑/썸/연인 초기/연인 안정기/부부/재회 6 관계별 톤 혼용 금지. 각 sub의 관계 톤을 정확히 따름.

L. **가독성 강조**
   - 별표(\`**\`)·물결·백틱·이모지 등 다른 마크다운 강조 절대 사용 금지.
   - 사용 가능한 단 한 가지 마커: \`[[텍스트]]\` → 핵심 강조 (골드색).
   - 각 소제목 본문 전체에서 1~2회만.
   - 마커 안에는 짧은 텍스트만 (10자 이내). 한 문장 통째 감싸지 말 것.

M. **모든 문장 "~에요" 어미** — "~입니다" 사용 금지. 의료·법률·이혼·재산 분할 자문 X.

N. **본능궁합 sub 톤** (5장 본능 sub 한정) — 노골 묘사·19+ 콘텐츠 절대 금지. 결·기운·온도·리듬·끌림 자연 비유 중심. 한쪽 도구화·비하 X.
`;

