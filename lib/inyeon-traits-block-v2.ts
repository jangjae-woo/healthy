// promptBlock — 챕터별 텍스트 블록 조립
// ════════════════════════════════════════════════════════════════════
type ChapterScope = "ch1" | "ch2" | "ch3" | "ch4" | "ch5" | "ch6" | "ch7" | "ch8";

export function inyeonTraitsToPromptBlock(
  t: InyeonTraitsV2,
  aName: string,
  bName: string,
  scope: ChapterScope,
): string {
  if (t.ilganPair.length === 0 && t.dominantPair.length === 0 && t.weakPair.length === 0) {
    return "";
  }
  const lines: string[] = [];
  lines.push(`【두 사람 결합 결정론 키워드 풀 (${scope}) — 이 단어들에서만 인용. 임의 통설 금지】`);
  if (t.ilganPair.length > 0) {
    lines.push(`▸ 일간 결합 (${aName} ${t.aIlgan} × ${bName} ${t.bIlgan}${t.ganhap ? " · 정합" : ""}): ${t.ilganPair.join(" / ")}`);
  }
  // ch3·ch4 — 성격·감정 — dominantPair 중심
  if ((scope === "ch3" || scope === "ch4") && t.dominantPair.length > 0) {
    lines.push(`▸ 강한 오행 결합 (${aName} ${t.aTopElem}강 × ${bName} ${t.bTopElem}강): ${t.dominantPair.join(" / ")}`);
  }
  // ch5·ch6 — 깊은결·재물 — weakPair 중심
  if ((scope === "ch5" || scope === "ch6") && t.weakPair.length > 0) {
    lines.push(`▸ 약한 오행 결합 (${aName} ${t.aWeakElem}약 × ${bName} ${t.bWeakElem}약 — 함께 보충 필요): ${t.weakPair.join(" / ")}`);
  }
  // ch2·ch7·ch8 — 인연·미래·편지 — 모두 활용
  if ((scope === "ch2" || scope === "ch7" || scope === "ch8") && t.dominantPair.length > 0) {
    lines.push(`▸ 강한 오행 결합: ${t.dominantPair.join(" / ")}`);
  }
  if (t.relationshipTone.length > 0) {
    lines.push(`▸ 관계 톤: ${t.relationshipTone.join(" / ")}`);
  }
  return lines.join("\n") + "\n";
}
