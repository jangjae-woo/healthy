// derive — 두 사주에서 인자 추출
// ════════════════════════════════════════════════════════════════════
function topElement(s: SajuAnalysis): string {
  return (Object.entries(s.elements) as [string, number][]).sort((a, b) => b[1] - a[1])[0][0];
}
function weakElement(s: SajuAnalysis): string {
  return (Object.entries(s.elements) as [string, number][]).sort((a, b) => a[1] - b[1])[0][0];
}

export interface InyeonTraitsV2 {
  ilganPair: string[];
  dominantPair: string[];
  weakPair: string[];
  ganhap: boolean;
  relationshipTone: string[];
  aIlgan: string;
  bIlgan: string;
  aTopElem: string;
  bTopElem: string;
  aWeakElem: string;
  bWeakElem: string;
}

export function deriveInyeonTraits(
  a: SajuAnalysis,
  b: SajuAnalysis,
  relationship: RelationshipKind,
): InyeonTraitsV2 {
  const aIlgan = a.ilgan;
  const bIlgan = b.ilgan;
  const aTopElem = topElement(a);
  const bTopElem = topElement(b);
  const aWeakElem = weakElement(a);
  const bWeakElem = weakElement(b);
  const ilganPair = ILGAN_PAIR_KEYWORDS[`${aIlgan}${bIlgan}`] ?? [];
  const dominantPair = ELEM_DOMINANT_PAIR[`${aTopElem}-${bTopElem}`] ?? [];
  const weakPair = ELEM_WEAK_PAIR[`${aWeakElem}-${bWeakElem}`] ?? [];
  const ganhap = GANHAP[aIlgan] === bIlgan;
  const relationshipTone = RELATIONSHIP_TONE[relationship] ?? [];
  return {
    ilganPair, dominantPair, weakPair, ganhap, relationshipTone,
    aIlgan, bIlgan, aTopElem, bTopElem, aWeakElem, bWeakElem,
  };
}

