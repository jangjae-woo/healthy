/**
 * 자녀가 보유한 신살 목록에서 어휘 매핑 표 생성 (dataBlock 박힘용).
 * @param sinsalNames 자녀 보유 신살 이름 배열 (예: ["천을귀인", "도화살"])
 */
export function buildSinsalVocabBlock(sinsalNames: string[] | undefined): string {
  if (!sinsalNames || sinsalNames.length === 0) {
    return `[★ 신살 어휘 매핑] 자녀 보유 신살 없음. 본문에 신살 인용 X.`;
  }
  const lines: string[] = [];
  for (const name of sinsalNames) {
    const entry = SINSAL_VOCAB[name];
    if (!entry) continue;
    lines.push(`- ${name} = ${entry.meaning} (어휘 예: ${entry.vocab.map((v) => `"${v}"`).join(" / ")})`);
  }
  if (lines.length === 0) {
    return `[★ 신살 어휘 매핑] 자녀 보유 신살 매핑 데이터 없음. 본문에 신살명만 그대로 인용.`;
  }
  return `[★ 신살 어휘 매핑 — 자녀 보유 신살. 풀 대명사 치환 시 반드시 이 어휘 사용]
${lines.join("\n")}
⚠️ 신살 본문 노출 룰 (V2.1.4):
  1회: 신살명 한자병기 (예: "천을귀인(天乙貴人)")
  2회: 신살명만 (예: "천을귀인이 자리해")
  3회+: 위 어휘로 치환 (예: "귀인 곁의 자리")
⚠️ "앞서 본 신살"·"앞서 짚은 신살"·"신살 중 앞서 본 신살" 같은 추상 풀 대명사 절대 X.`;
}
