/**
 * 프롬프트에 박힐 메커니즘 풀 룰 생성.
 * route.ts ch*Body 안 ${injectMechanism("wood_excess", 1)} 형태로 호출.
 *
 * 깨달음 포인트 4단 연결 의무:
 * ① 사주 인자 명시 → ② 풀에서 자연 비유 1개 인용 → ③ 결과 현상 → ④ 일상·마음 번역
 */
export function injectMechanism(key: MechanismKey, pickCount: number = 1): string {
  const pool = MECHANISM_POOL[key]
  if (!pool || pool.length === 0) return ""
  const formatted = pool.map((m) => `- "${m}"`).join("\n")
  return `[메커니즘 풀 — ${key} (깨달음 포인트용)]
다음 풀 안에서 ${pickCount}개 골라 본문에 자연 비유로 인용. 즉흥 생성 금지.
같은 오행 본문 안 2회 이상 등장 시 매번 다른 항목 선택 의무 — ctrl+v 금지.

${formatted}

⚠️ 4단 연결 의무: 사주 인자 명시 → 위 풀 비유 인용 → 결과 현상 → 일상·마음 번역 (예: "나무 많음 → 빽빽한 숲 → 햇빛 못 닿음 → 마음 답답함")`
}

