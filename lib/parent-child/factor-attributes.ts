/**
 * 프롬프트에 박힐 인자 속성 룰 생성.
 * route.ts ch*Body 안 ${injectFactorAttribute("비겁", "ch3")} 형태로 호출.
 */
export function injectFactorAttribute(factor: FactorId, chapter: ChapterDomain): string {
  const attr = FACTOR_ATTRIBUTES[factor]?.[chapter]
  if (!attr) {
    return `[인자 속성 매트릭스] ${factor}은(는) 본 챕터(${chapter})에서 직접 노출 금지 인자. 다른 인자 사용.`
  }
  return `[인자 속성 매트릭스 — ${factor}의 ${chapter} 영역 작동 속성]
${attr}

→ 위 속성만 본문에 표현. 다른 챕터 영역 속성(예: ${factor}이 다른 챕터에서 갖는 결)으로 풀이 침범 절대 X.`
}
