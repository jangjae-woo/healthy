/**
 * 프롬프트에 박힐 가정문 풀 룰 생성.
 * route.ts ch*Body 안 ${injectScenario("ch3_calm_light", 1)} 형태로 호출.
 * @param key 가정문 카테고리
 * @param pickCount 본문에 의무 노출할 항목 수
 */
export function injectScenario(key: ScenarioKey, pickCount: number = 1): string {
  const pool = SCENARIO_POOL[key]
  if (!pool || pool.length === 0) return ""
  const formatted = pool.map((s) => `- "${s}"`).join("\n")
  return `[가정문 풀 — ${key}]
다음 풀 안에서만 ${pickCount}개 골라 본문에 노출. 즉흥 가정문 생성 절대 금지.
풀 외 새 가정문 만들면 톤이 비슷해도 위반.

${formatted}

⚠️ 자녀 사주 결에 가장 맞는 항목 선별. 풀 항목 그대로 또는 자연 변주로 인용.`
}
