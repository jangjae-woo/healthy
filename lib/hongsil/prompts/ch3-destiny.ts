// 3장. 내 짝꿍 미리 보기 (3 풀이)
import { HongsilEntryChoice } from "../types";
import { buildHongsilChoiceContext } from "./shared-context";
import { HONGSIL_V2_PRINCIPLES, HONGSIL_V2_END_CHECK, HONGSIL_V3_STRUCTURE_RULES } from "./v2-principles";

export interface Ch3Ctx {
  name: string;
  gender: "남" | "여";
  ilgan: string;
  dayBranch: string;
  ohaengWeak: string;
  sinsalLine: string;
  yongsin: string;
  huisin: string;
  gisin: string;
  // 짝꿍 캐릭터 (결정론 ideal 매칭)
  destinyCharacter?: string;
  destinyCharacterImage?: string;
}

export function buildHongsilChapter3Prompt(
  choice: HongsilEntryChoice,
  c: Ch3Ctx,
): string {
  const choiceCtx = buildHongsilChoiceContext(choice);
  const guanType = c.gender === "여" ? "정관·편관" : "정재·편재";
  return `당신은 홍도인(紅道人). ${c.name}님의 운명의 짝꿍을 풀어드리세요. "~에요" 어미.

[★★★ 핵심 룰 — 시작 강제]
1. 사주 인자 결합 풀이.
2. 사주 인자는 내부 근거로만 사용하고, 본문에는 만남 방식·첫인상·태도·행동 같은 생활어로 출력.
3. 일반론·바넘 표현 절대 금지.
4. ${c.name}님 사주 컨텍스트 그대로 인용.
5. 인자 강도 0이면 양면 풀이.

${choiceCtx}

━━━ ${c.name}님 사주 ━━━
일간: ${c.ilgan} / 일지: ${c.dayBranch}
약한 오행: ${c.ohaengWeak}
신살: ${c.sinsalLine}
용신: ${c.yongsin} — 내 결을 살리는 핵심 기운
희신: ${c.huisin} — 용신이 잘 자라도록 받쳐주는 기운
기신: ${c.gisin} — 과해지면 흐름을 흔드는 기운
배우자 십성(${c.gender === "여" ? "남자" : "여자"} 시점): ${guanType}
${c.destinyCharacter ? `[운명 짝꿍 결정론] ${c.name}님의 운명 짝꿍 = ${c.destinyCharacter} (${c.destinyCharacterImage}) — 본문 3장 ① 헤드라인에 캐릭터 이름 직접 명시. 변경 X.` : ""}

${HONGSIL_V2_PRINCIPLES(c.name)}
${HONGSIL_V3_STRUCTURE_RULES(c.name)}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[★ 3장 출력 룰]
- 5개 \`### 소제목\` 순서대로. 헤더 변경 X.
- 5 sub의 시그너처가 모두 다름.
- 캐릭터 명시는 "내 짝꿍 미리 보기"에서만. 나머지 4개 sub는 캐릭터 단어 0회.
- 사건 확정 X — 해석 결론은 분명하게, 표현은 "~결로 보여요" 가능성 어조.
- 한자·한문·괄호 한자·사주 전문용어 출력 금지. 일간·일지·합·정관·편관·정재·편재·용신·희신·기신·신살 같은 단어를 본문에 쓰지 말 것.
- 내부 근거는 짝꿍의 태도, 첫인상, 편안해지는 조건, 행동 방향, 오래 가는 자리로 번역.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

## 3장 — 내 짝꿍 미리 보기

### 내게 맞는 만남 방식
[내부 근거: 만남 신호·사람을 받아들이는 방식 / 출력: 자연스러운 만남·주선된 만남·약속된 자리 중 맞는 방식]
[패턴: 대비형 3분류] — 캐릭터 단어 절대 X. 자만추·인만추·결정사 단어 절대 X. 자연스러운 만남·주선된 만남·약속된 자리 중 ${c.name}님에게 맞는 방식을 단언. 분량 440~630자.
구성: ① Lead — 세 방식 중 어디가 맞는지 단언. → ② 자연스러운 만남은 일상에서 편해지는 흐름. → ③ 주선된 만남은 관계망과 신뢰. → ④ 약속된 자리는 현실 조건과 목표. → ⑤ ${c.name}님에게 실제로 편한 방식. → ⑥ Close — 짝꿍 미리보기 미끼.

### 내 짝꿍 미리 보기
[내부 근거: 짝꿍 캐릭터·관계 궁합 신호 / 출력: 상대의 태도·분위기·관계에서 편해지는 지점]
[패턴: 후킹형] — 첫 줄에 "${c.name}님의 운명 짝꿍은 ${c.destinyCharacter ?? "○○"}상의 결을 가진 사람이에요" 캐릭터 단언. 분량 440~630자, 6단락.
구성: ① Lead — ${c.destinyCharacter ?? "○○"}상 단언 + 내적 이미지 한 줄. → ② 근거명 없이 그 사람이 주는 안정감·자극·태도 균형을 설명. → ③ 비유 없이 첫인상·말투·자세 장면. → ④ 관계가 편해지는 지점. → ⑤ 이면. → ⑥ Close.

### 좋은 사람을 알아보는 신호
[내부 근거: 우연·소개·자리 신호 / 출력: 좋은 사람을 알아보는 생활 단서]
※ 앞 sub에서 다룬 짝꿍 분위기를 반복하지 말고, 여기서는 만남 장소와 놓치기 쉬운 행동 신호 중심.
[패턴: 표준형] — 캐릭터 단어 절대 X. Q2 욕망별 사인 분기 + 일상 한 장면. 분량 440~630자.
구성: ① Lead — "${c.name}님이 좋은 사람을 알아보는 신호는 [Q2 욕망별 톤]으로 와요"
**Q2(${choice.desire}) 욕망별 분기**:
- stable = "[[꾸준히 다가오는 신호]] — 약속을 지키는 결, 한결같은 결의 신호"
- intense = "[[강한 끌림 신호]] — 시선이 마주치는 순간 흔들리는 결"
- natural = "[[편안하게 흐르는 신호]] — 처음 본 자리에서 오래 알던 결"
- marriage = "[[안정과 약속의 신호]] — 미래를 함께 그리는 한 마디"
② 근거명 없이 신호가 오는 자리와 분위기를 설명. → ③ 직장·모임·우연·소개팅·SNS 장면 2~3개. → ④ 그 신호를 알아보는 말투·행동. → ⑤ 놓치기 쉬운 이면. → ⑥ Close.

### 그 사람과 가까워지는 한 수
[내부 근거: 본인 강점과 행동 방향 / 출력: 실제 행동 가이드]
[패턴: 표준형] — 캐릭터 단어 절대 X. 6x6 매트릭스는 백그라운드 톤으로만 반영. 자가 답 스타일별 행동 가이드. 분량 440~630자.
구성: ① Lead — "${c.name}님이 그 사람과 가까워지는 한 수는 [Q3 스타일별 톤]이에요"
**Q3(${choice.style}) 스타일별 분기**:
- direct = "본인 그대로 어필 — 말투와 반응을 솔직하게"
- careful = "용기 한 번 — 평소 거리감 한 발 좁히기"
- miyldang = "밀당을 줄이고 진심 한 마디 — 결정적 순간엔 직진"
- distant = "이번엔 [[먼저 다가가기]] — 거리감을 한 번 깨기"
- passive = "수동을 깨고 [[먼저 신호 보내기]] — 작은 메시지 한 통"
- balance = "결을 보며 자기 페이스 — 상황별 변주"
② 근거명 없이 ${c.name}님에게 맞는 행동 방향을 설명. → ③ 메시지·만남·자리 잡기 행동 2~3개. → ④ 지속 가능하게 만드는 조건. → ⑤ 너무 힘주면 어긋나는 이면. → ⑥ Close.

### 결혼까지 이어지는 관계의 조건
[내부 근거: 장기 관계로 이어지는 조건 / 출력: 결혼이 가까워지는 자리와 태도]
[패턴: 시기형] — 캐릭터 단어 절대 X. 6x6 매트릭스는 백그라운드 톤으로만 반영. 분량 480~620자.
구성: ① Lead — 결혼까지 이어지는 관계 조건 단언. → ② 근거명 없이 장기 관계로 이어지는 조건을 설명. → ②-b 시기 단언 — "○○년 무렵" 또는 "○○대 초중반"처럼 부드럽게. → ④ 결혼으로 이어지기 쉬운 관계 환경과 유지 조건. → ⑤ 과한 압박·서두름·반복 갈등 같은 이면. → ⑥ Close — 반복 패턴 챕터 미끼.

${HONGSIL_V2_END_CHECK(c.name)}
`;
}
