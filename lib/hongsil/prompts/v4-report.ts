import { HongsilEntryChoice } from "../types";
import { buildHongsilChoiceContext } from "./shared-context";

type AnyCtx = Record<string, string | number | undefined>;

function sharedV4Rules(name: string) {
  return `
[★★★★★ 홍실 V4 새 구조 원칙]
목표: 사주를 모르는 사람도 앞에서 배우고, 뒤에서는 술술 읽히게 만든다.

1. 초반 안내와 본문 해석 분리
- ch1의 "내 매력은?"은 근거 공개 페이지다. 여기서만 사주 인자, 한자 병기, 원국/오행/십성/용신 계열 핵심 근거를 최소로 공개한다.
- ch1의 두 번째 소제목부터 ch6까지는 사주 전문용어를 다시 반복하지 않는다.
- 이후 본문은 이미 공개된 근거를 읽은 독자에게 이어 말하듯, 생활 장면과 감정 반응으로만 풀어쓴다.

2. 같은 인자를 다시 쓸 때의 깊이 규칙
- 같은 근거를 쓰더라도 같은 결론을 반복하지 않는다.
- 첫인상에서는 "밖으로 보이는 모습", 호감 신호에서는 "티 나는 행동", 사랑 태도에서는 "관계 안 변화", 위험 패턴에서는 "흔들리는 순간", 가이드는 "실제 행동"만 다룬다.
- 같은 사주 근거 + 같은 생활어 + 같은 결론이면 중복이다. 그 문장은 삭제하고 다음 깊이로 들어간다.

3. 한자와 전문용어 노출
- "내 매력은?" 외에는 한자, 괄호 한자, 60갑자 한자, 일간, 일주, 십성, 비겁, 식상, 재성, 관성, 인성, 신약, 신강, 용신, 희신, 기신, 신살명을 출력하지 않는다.
- 필요하면 다음 생활어로 바꾼다: 말투, 반응, 속도, 기준감, 거리감, 안정감, 표현 방식, 약속, 조율, 회복, 선택.

4. 초보자 친절함
- 어려운 말을 쓰면 바로 다음 문장에서 쉬운 말로 풀어야 한다. 단, ch1 첫 소제목 이후에는 어려운 말을 쓰지 않는다.
- 표처럼 읽히는 문장을 섞는다. 예: "말투는 천천히, 반응은 세심하게, 선택은 신중하게 움직이는 편이에요."
- 독자가 자기 상황을 떠올릴 수 있는 장면을 넣는다. 단, 카페 예시는 한 결과물 안에서 1회 이하.

5. 비유와 상징 제한
- 동물 상징 금지. "닭처럼", "용처럼", "쥐처럼" 같은 표현 금지.
- 자연 비유는 ch1에서만 아주 짧게 허용한다. ch2 이후는 실제 말투, 행동, 연락, 약속, 관계 흐름으로 쓴다.
- "고요한 호수", "꽃봉오리", "강물" 같은 장식적 비유를 길게 쓰지 않는다.

6. 문장 품질
- 모든 문장은 "~에요" 어미를 기본으로 한다. "~입니다" 금지.
- "다만" 남발 금지. 전환어는 "주의할 점은", "반대로", "이럴 때는", "그래서" 중 문맥에 맞게 쓴다.
- "자기 리듬을 천천히 세우는 결" 같은 문구를 반복하지 않는다.
- "회복기를 거치는 결", "흐름한 결", "부담감을 자기 리듬을" 같은 비문 금지.

7. 개인화
- ${name}님 호칭을 정확히 쓴다. 단독 이름 금지.
- 일반론 금지. 다른 사람에게 그대로 붙여도 통하는 문장은 실패다.
- 선택지 답변을 억지로 끼워 넣지 말고, 해당 파트에서 자연스러운 경우에만 반영한다.

8. 출력 형식
- 요청된 ### 소제목을 한 글자도 바꾸지 않는다.
- 각 소제목 본문은 5~6단락, 430~650자.
- 강조는 [[짧은 핵심어]]만 소제목당 1~2회 사용한다.
`;
}

function endCheck(name: string) {
  return `
[출력 직전 점검]
- ${name}님 사주 근거와 선택 답변을 임의로 바꾸지 않았는가?
- "내 매력은?" 외에 한자/전문용어가 남아 있지 않은가?
- 같은 근거를 같은 말로 반복하지 않고 더 깊은 장면으로 들어갔는가?
- 카페 예시, 자연 비유, "다만", "자기 리듬"이 반복되지 않는가?
- 한 문장이라도 비문이면 자연스러운 한국어로 고쳤는가?
- 모든 헤더가 정확히 ### 로 시작하는가?
`;
}

