function v5Principles(name: string) {
  return `
[★★★★★ 홍실 V5 역설계형 출력 원칙]

목표:
- 독자가 "이 말은 AI가 지어낸 말이 아니라 내 사주표의 근거에서 나온 해석이구나"라고 느끼게 한다.
- 초반에는 070 이미지처럼 한문과 해석을 자연스럽게 섞어 사주 근거를 보여주고, 중반 이후에는 그 근거를 생활 장면으로 깊게 풀어쓴다.

1. 근거 제시 공식
- 중요한 본문은 반드시 "감각적 결론 -> 한문이 섞인 사주 근거 -> 자리 설명 -> 쉬운 번역 -> 연애 장면 -> 이면/가이드" 순서로 쓴다.
- 사주 근거는 한 번에 2~4개만 쓴다. 너무 많이 나열하지 않는다.
- 사주 근거를 쓰면 바로 쉬운 말로 풀어준다.
- 예시 구조:
  "${name}님은 처음엔 차분하지만 가까워질수록 기준이 분명한 사람으로 느껴지는 편이에요.
   이는 ${name}님의 일간(나를 상징하는 기운)이 갑목(甲木)이고, 일지(마음 안쪽과 배우자궁을 보는 자리)에 특정 기운이 놓여 있기 때문이에요.
   쉽게 말하면, 겉으로 보이는 분위기와 마음 안쪽의 반응 방식이 함께 이런 인상을 만드는 거예요."

2. 전문용어 노출 단계
- ch1의 "내 매력은?"은 근거 공개 페이지다. 여기서는 일간, 일지, 월지, 오행, 십성, 용신/희신/기신 중 필요한 근거를 최소 노출한다.
- ch1의 나머지 소제목도 070 이미지처럼 신뢰가 필요한 첫 문단에서는 한문 병기 근거 1~2개를 허용한다. 단, 반드시 괄호 안에 자리 설명과 쉬운 해석을 붙인다.
- ch2~ch3의 첫 소제목 또는 핵심 본문은 한문 병기 근거 1~2개를 제한적으로 허용한다. 이후 반복 파트는 생활어로만 쓴다.
- ch4~ch6은 전문용어 직접 노출을 피한다. 필요하면 "앞서 본 기준감", "관계 속도", "표현 방식", "마음의 안전감"처럼 생활어로 쓴다.
- 한자가 문제인 것이 아니라 설명 없이 방치되는 것이 문제다. 한문을 썼으면 같은 문단에서 반드시 초보자용 해석을 붙인다.

3. 초보자 친절함
- 어려운 단어가 나오면 같은 문장이나 바로 다음 문장에서 쉬운 뜻을 붙인다.
- "일간은 나를 상징하는 기운", "일지는 마음 안쪽과 관계의 바닥", "월지는 사회적으로 보이는 모습"처럼 자리의 뜻을 풀어준다.
- "배우자궁은 연애와 깊은 관계에서 내가 편해지는 자리", "십성은 관계 안에서 작동하는 역할", "오행은 성향의 재료"처럼 독자가 모르는 말을 반드시 번역한다.
- 독자가 사주를 몰라도 읽히도록 용어보다 설명이 길어야 한다.

4. 중복 회피
- 같은 사주 근거를 반복해도 같은 결론을 반복하지 않는다.
- "내 매력은?"은 예외다. 이 파트에는 전체 핵심 한문 근거가 모두 나올 수 있다.
- "내 매력은?" 이후에는 이미 한 번 나온 한문 병기와 사주근거명을 다시 쓰지 않는다. 파트가 달라도 반복 금지다.
- 예: "내 매력은?" 또는 이전 소제목에서 일간(甲木), 일지, 갑목(甲木)을 썼다면 이후 소제목에서는 그 인자명을 직접 호출하지 말고 그 인자가 만드는 행동·말투·반응을 일상 장면으로 바로 보여준다.
- 각 소제목에서 허용되는 1~3개의 한문/사주근거는 "아직 본문에서 쓰지 않은 새 근거"여야 한다.
- 첫인상은 밖으로 보이는 모습, 호감 신호는 좋아할 때 새는 행동, 사랑 태도는 관계에 들어간 뒤 변화, 위험 패턴은 흔들리는 순간, 가이드는 실제 행동만 다룬다.
- "신중하다", "섬세하다", "배려한다", "편안하다", "기준감" 같은 생활어도 같은 소제목 안에서 반복하지 않는다.

5. 문장 품질
- 모든 문장은 "~에요" 어미를 기본으로 한다. "~입니다" 금지.
- "다만" 남발 금지. 전환은 "주의할 점은", "반대로", "이럴 때는", "그래서"를 자연스럽게 쓴다.
- 동물 비유 금지. "닭처럼", "용처럼", "쥐처럼" 같은 표현 금지.
- 과한 자연 비유 금지. 감정 장식보다 실제 말투, 연락, 약속, 관계 장면을 쓴다.

6. 개인화
- ${name}님 호칭을 정확히 쓴다. 단독 이름 금지.
- 일반론 금지. 다른 사람에게 그대로 붙여도 통하는 문장은 실패다.
- 선택지 답변은 해당 파트와 자연스럽게 맞을 때만 반영한다.

7. 형식
- 요청된 ### 소제목을 한 글자도 바꾸지 않는다.
- 각 소제목은 5~6단락, 430~680자.
- 강조는 [[짧은 핵심어]]만 소제목당 1~2회 쓴다.
`;
}

function finalCheck(name: string) {
  return `
[출력 직전 체크]
- ${name}님 사주 데이터에서 나온 근거를 썼는가?
- 070 이미지처럼 한문과 해석이 자연스럽게 섞인 신뢰형 문장이 들어갔는가?
- 한문 근거를 쓰자마자 자리 설명과 쉬운 말로 번역했는가?
- 같은 근거를 같은 결론으로 반복하지 않았는가?
- "내 매력은?" 이후에 이미 등장한 한문 병기/사주근거명이 다시 등장하지 않았는가?
- 한자를 없애는 데 치우치지 않고, 필요한 곳에는 갑목(甲木), 유금(酉金), 일간, 일지처럼 근거를 보여줬는가?
- 카페 예시, 자연 비유, "다만", "자기 리듬"이 반복되지 않았는가?
- 헤더는 정확히 ### 로 시작하는가?
`;
}

